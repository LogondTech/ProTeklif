export function getOfferTexts(language) {
  const base = copies.en;
  const localized = copies[language] || base;
  const preview = previewCopy[language] || previewCopy.en;

  return {
    ...base,
    ...localized,
    ...previewCopy.en,
    ...preview,
    statuses: { ...base.statuses, ...localized.statuses },
    templates: { ...previewCopy.en.templates, ...preview.templates },
    templateDescriptions: {
      ...previewCopy.en.templateDescriptions,
      ...preview.templateDescriptions,
    },
  };
}

export function getOffersLocale(language) {
  return localeByLanguage[language] || localeByLanguage.en;
}

export function getStoredPdfTemplate() {
  try {
    const stored = globalThis.localStorage?.getItem(PDF_TEMPLATE_STORAGE_KEY);
    return PDF_TEMPLATES.some((template) => template.id === stored)
      ? stored
      : DEFAULT_PDF_TEMPLATE;
  } catch {
    return DEFAULT_PDF_TEMPLATE;
  }
}

export function storePdfTemplate(templateId) {
  if (!PDF_TEMPLATES.some((template) => template.id === templateId)) return;
  try {
    globalThis.localStorage?.setItem(PDF_TEMPLATE_STORAGE_KEY, templateId);
  } catch {
    // The in-memory selection still works when storage is unavailable.
  }
}
